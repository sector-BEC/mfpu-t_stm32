
#ifndef INC_LOGIC_H_
#define INC_LOGIC_H_

#include <stdint.h>
#include <stdbool.h>

/* Инициализация модуля логики (настройка HI-3220, начальное состояние). */
void Logic_Init(void);

/* Вызывается из СЛОТА 1 (каждую 1 мс) -- короткие критичные по времени
 * действия: опрос клавиатуры/датчиков, обновление таймеров с разрешением 1мс.
 * Должно укладываться в 500 мкс. */
void Logic_Tick1ms(void);

/* Вызывается из СЛОТА 2 (каждые 10 мс) -- обмен по сети:
 * опрос RX FIFO, диспетчеризация входящих слов, отправка периодики,
 * обработка повторов сообщений №1. */
void Logic_Process(void);

/* Событие клавиатуры от драйвера сканирования клавиш (вызывается из
 * Logic_Tick1ms или напрямую из обработчика сканера). Ставит в очередь
 * сообщение №1 на активную линию. */
void Logic_KeyEvent(uint8_t key_code);

#endif /* INC_LOGIC_H_ */
