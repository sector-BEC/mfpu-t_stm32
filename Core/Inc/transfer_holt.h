void TRANSFER_SendImmediate(uint8_t channel, const uint8_t *data);

// Запись слова в память (низкоуровневая)
void TRANSFER_WriteWord(uint16_t addr, uint8_t *data);

// Управление loopback (маска каналов + автоматическая установка бита LOOP в MCR)
void TRANSFER_SetLoopback(uint8_t mask);

void Init_Holt(SPI_HandleTypeDef *hspi,
		GPIO_TypeDef *cs_port, uint16_t cs_pin,
        GPIO_TypeDef *mrst_port, uint16_t mrst_pin,
        GPIO_TypeDef *run_port, uint16_t run_pin);

/*
 * Согласно datasheet holt hi-3220:
 * Команда 0x88 (write memory at address MAP) не принимает адрес в том же кадре. Она использует предварительно загруженный указатель MAP.
 * Команда 0x80 (read memory at address MAP) – аналогично.
 * Для записи в произвольный адрес нужно:
 * Загрузить MAP командой 0x98 + 2 байта адреса (старший, младший).
 * Затем отправить 0x88 + байт данных.
 *
 *
 * SPI режим – обязательно Mode 0 (CPOL=0, CPHA=0) или Mode 3 (CPOL=1, CPHA=1).
 * В STM32 это SPI_FIRSTBIT_MSB, полярность и фаза по выбору.

 **** ОБНОВИТЬ ИНФОРМАЦИЮ ДЛЯ НОВОГО HOLT-HI3220 (УСТАРЕЛО) ****
 *** Регистры и ARINC, взаимодействие STM32 <-> HOLT ***
 Правильное аппаратное подключение:
 * SPI настроен в режим 0 или 3, частота до 20 МГц, MSB first.
 * Пины CS, MRST, RUN правильно инициализированы и подключены к HI-3210.
 * Пин AACK – если он привязан к VDD (как часто делают), то AINT будет выдавать короткий импульс (~1 мкс). Для удержания уровня нужно управлять AACK через GPIO.
 * Внешние ARINC интерфейсы: HI-3210 работает с внешними приёмниками HI-8448 и драйверами HI-8592/8596 (см. стр. 1 даташита). Без них физического обмена по ARINC429 не будет, но SPI-регистры читаются/пишутся.


 **** ОБНОВИТЬ ИНФОРМАЦИЮ ДЛЯ НОВОГО HOLT-HI3220 (УСТАРЕЛО) ****
 * Как происходит взаимодействие:
 * STM32 через SPI конфигурирует HI-3220 (регистры, таблицы фильтров).
 * Затем HI-3210 самостоятельно принимает/передаёт ARINC-сообщения по своим линиям.
 * Когда приходит новое сообщение, HI-3210 сохраняет его в свою внутреннюю RAM (по адресу (канал*256 + метка)*4).
 * STM32 может в любой момент прочитать эти данные через SPI (командой 0xC0RRR00 или прямым доступом к MAP).
 * Для отправки STM32 пишет 4 байта через команду 0x94TT (немедленная передача) или через дескрипторы планировщика.
 */

#endif /* INC_TRANSFER_HOLT_H_ */

/*
 *** Общая информация ***
 *
 * 1. SPI интерфейс
 * Режим SPI: Mode 0 (CPOL=0, CPHA=0) или Mode 3 (CPOL=1, CPHA=1) – автоматически совместим.
 * Команды – 8‑битные опкоды, затем данные (CS активен низким уровнем).
 * Fast-access команды для регистров 0x8000…0x800F: чтение 00RRRR00 (0x00…0x3C), запись 01RRRR00 (0x40…0x7C).
 * Косвенный доступ через 16‑битный Memory Address Pointer (MAP):
 * - Запись MAP: 0x8C + 2 байта адреса (старший, младший).
 * - Чтение MAP: 0x88 – возвращает 2 байта.
 * - Чтение памяти по MAP: 0x80 – после этой команды MAP автоматически инкрементируется.
 * - Запись памяти по MAP: 0x84 – MAP также инкрементируется.
 *
 * Специальные команды:
 * - 0x94…0x97 – немедленная передача ARINC слова (канал 0…3).
 * - 0xC0…0xDC – чтение блока приёмного канала (по прерыванию).
 * - 0xA0…0xBC – чтение FIFO канала.
 * - 0xE0…0xFC – чтение сообщения и метки.
 *
 * 2. Организация памяти приёма
 * Каждый канал имеет 256 записей (по метке) по 4 байта:
 * - Байт 0 – статус (биты NEWHOST, NEWTX0..3 и т.д.).
 * - Байты 1,2,3 – полезные данные (bits 9‑32). Адрес = (channel * 256 + label) * 4.
 *
 * 3. Управление потоком
 * - Регистр MCR (0x800F): бит 0 – включить приём, бит 1 – переворот меток (AFLIP), бит 2 – включить передачу.
 * - Регистры ARXC0…7 (0x8010…0x8017) – настройка приёмных каналов: enable, скорость, parity, декодер, условие флага FIFO.
 * - Регистры ATXC0…3 (0x8018…0x801B) – настройка передатчиков: run/stop, скорость, parity, skip.
 * - Вход RUN – глобальное разрешение работы (HIGH = активен).
 **/
